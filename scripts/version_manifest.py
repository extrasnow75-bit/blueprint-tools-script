#!/usr/bin/env python3
"""Keeps version stamps and version-manifest.json in step with each file's
"Last updated on" header. Blueprint Tools Version Check (Code14.gs) compares the
stamps inside a user's copy of the script with this manifest on master.

  python3 scripts/version_manifest.py --sync    rewrite stamps and the manifest from the headers
  python3 scripts/version_manifest.py --check   exit 1 if anything disagrees (use before committing)

Rules: every Code*.gs and Sidebar*.html file is listed, except Spikes.gs
(throwaway). A .gs file carries `var BP_VER_<name> = 'YYYY-MM-DD HH:MM';` right
after its header comment; an .html file's stamp is its own header comment.
Time zone labels (MDT/MST) in the headers are ignored.
"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER_RE = re.compile(r'Last updated on (\d{4}-\d{2}-\d{2}) at (\d{2}:\d{2})')
SKIP = {'Spikes.gs'}


def files():
    out = []
    for pat in ('Code*.gs', 'Sidebar*.html'):
        for p in sorted(glob.glob(os.path.join(ROOT, pat))):
            if os.path.basename(p) not in SKIP:
                out.append(p)
    return out


def header_stamp(text):
    m = HEADER_RE.search(text)
    return '%s %s' % (m.group(1), m.group(2)) if m else None


def stamp_var(name):
    return 'BP_VER_' + os.path.splitext(name)[0]


def gs_insert_index(lines):
    """First line after the leading comment block (// lines, /* */ blocks, blanks)."""
    in_block = False
    for i, l in enumerate(lines):
        s = l.strip()
        if in_block:
            if '*/' in s:
                in_block = False
            continue
        if s.startswith('/*'):
            if '*/' not in s:
                in_block = True
            continue
        if s == '' or s.startswith('//'):
            continue
        return i
    return len(lines)


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else '--check'
    problems, manifest = [], {}
    for p in files():
        name = os.path.basename(p)
        text = open(p, encoding='utf-8').read()
        stamp = header_stamp(text)
        if not stamp:
            problems.append('%s: no "Last updated on YYYY-MM-DD at HH:MM" header' % name)
            continue
        manifest[name] = stamp
        if name.endswith('.gs'):
            var = stamp_var(name)
            line_re = re.compile(r"^var %s = '([^']*)';.*$" % var, re.M)
            m = line_re.search(text)
            want = "var %s = '%s';  // keep equal to \"Last updated on\" above; Code14.gs reads it" % (var, stamp)
            if mode == '--sync':
                if m:
                    text = line_re.sub(want, text, count=1)
                else:
                    lines = text.split('\n')
                    i = gs_insert_index(lines)
                    lines[i:i] = [want, '']
                    text = '\n'.join(lines)
                open(p, 'w', encoding='utf-8').write(text)
            elif not m or m.group(1) != stamp:
                problems.append('%s: %s is %s, header says %s' % (name, var, m.group(1) if m else 'missing', stamp))
    out = json.dumps({'note': 'Generated by scripts/version_manifest.py --sync. Do not edit by hand.', 'files': manifest}, indent=2) + '\n'
    mp = os.path.join(ROOT, 'version-manifest.json')
    if mode == '--sync':
        open(mp, 'w', encoding='utf-8').write(out)
        print('Synced %d files.' % len(manifest))
    else:
        cur = open(mp, encoding='utf-8').read() if os.path.exists(mp) else ''
        if cur != out:
            problems.append('version-manifest.json is out of date (run --sync)')
    for pr in problems:
        print('PROBLEM:', pr)
    if problems and mode != '--sync':
        sys.exit(1)
    print('Version stamps OK.' if not problems else '')


main()
